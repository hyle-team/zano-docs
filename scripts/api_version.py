#!/usr/bin/env python3
"""Release lifecycle tool for the versioned RPC API reference.

The RPC reference is a separate Docusaurus docs instance (pluginId "api"):
  api-reference/            working dir  = Mainnet (current)
  api_versioned_docs/       placed snapshots (version-testnet, version-<release>)
  api_versioned_sidebars/   one sidebars json per snapshot
  api_versions.json         dropdown order below "current" (user-facing!)

Commands
  testnet  --zanod X --simplewallet Y --label L   regenerate the testnet snapshot
  archive  --name 2.2.1                           snapshot current mainnet as a release
  rollover --zanod X --simplewallet Y --label L   replace mainnet from a release binary
  check                                           validate invariants (CI-safe, no writes)

Rules encoded here (do not bypass):
  * generation goes to a temp dir first and is sanity-checked before replacing anything
  * rollover refuses to run unless an archive of the current content exists
  * hand-written files (the four intro pages, sidebars) are never overwritten by generation
  * api_versions.json is normalized to ["testnet", <archives newest-first>]
  * provenance (generator version stamp) must match the configured label
"""

import argparse
import json
import re
import shutil
import subprocess
import sys
import tempfile
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
WORK = ROOT / "api-reference"
VDOCS = ROOT / "api_versioned_docs"
VSIDE = ROOT / "api_versioned_sidebars"
VJSON = ROOT / "api_versions.json"
CONFIG = ROOT / "docusaurus.config.js"
INTRO_PAGES = ["overview.md", "how-to-call-api.md", "daemon-rpc.md", "wallet-rpc.md"]
SIDEBAR_TEMPLATE = {
    "apiSidebar": [
        {"type": "link", "label": "← Build documentation", "href": "/docs/build/overview"},
        {"type": "autogenerated", "dirName": "."},
    ]
}


def die(msg):
    print(f"ERROR: {msg}", file=sys.stderr)
    sys.exit(1)


def run_generator(binary, outdir):
    binary = Path(binary)
    if not binary.is_file():
        die(f"binary not found: {binary}")
    subprocess.run(
        [str(binary), f"--generate-rpc-autodoc={outdir}"],
        check=True, capture_output=True, timeout=300,
    )
    pages = list(Path(outdir).glob("*.md"))
    if len(pages) < 40:
        die(f"{binary.name} generated only {len(pages)} pages — sanity check failed")
    return pages


def stamp_of(md_dir):
    for f in sorted(Path(md_dir).glob("*.md")):
        m = re.search(r"Auto-doc built with: (\S+)</sub>", f.read_text(encoding="utf-8"))
        if m:
            return m.group(1)
    return None


def generate_pair(zanod, simplewallet):
    tmp = Path(tempfile.mkdtemp(prefix="api-gen-"))
    d, w = tmp / "daemon", tmp / "wallet"
    d.mkdir()
    w.mkdir()
    run_generator(zanod, d)
    run_generator(simplewallet, w)
    print(f"generated: {len(list(d.glob('*.md')))} daemon, {len(list(w.glob('*.md')))} wallet "
          f"(stamp {stamp_of(d)}) -> {tmp}")
    return d, w


def replace_generated(target_root, daemon_dir, wallet_dir):
    """Replace ONLY generated method pages; keep intros + category jsons."""
    for sub, src in (("daemon-rpc-api", daemon_dir), ("wallet-rpc-api", wallet_dir)):
        dst = target_root / sub
        cat = dst / "_category_.json"
        cat_backup = cat.read_text(encoding="utf-8") if cat.exists() else None
        for old in dst.glob("*.md"):
            old.unlink()
        for f in src.glob("*.md"):
            shutil.copy2(f, dst / f.name)
        if cat_backup is not None:
            cat.write_text(cat_backup, encoding="utf-8")


def set_config_label(version_key, label):
    t = CONFIG.read_text(encoding="utf-8")
    pattern = rf'({version_key}: \{{\n\s*label: ")[^"]*(")'
    new, n = re.subn(pattern, rf"\g<1>{label}\g<2>", t, count=1)
    if n != 1:
        die(f"could not update label for version '{version_key}' in docusaurus.config.js")
    CONFIG.write_text(new, encoding="utf-8")
    print(f"config: {version_key} label -> {label}")


def normalize_versions_json():
    versions = json.loads(VJSON.read_text(encoding="utf-8"))
    archives = sorted(
        [v for v in versions if v != "testnet"],
        key=lambda v: [int(x) for x in re.findall(r"\d+", v)],
        reverse=True,
    )
    ordered = (["testnet"] if "testnet" in versions else []) + archives
    VJSON.write_text(json.dumps(ordered) + "\n", encoding="utf-8")
    print(f"api_versions.json -> {ordered}")


def add_provenance(overview_path, stamp, extra=""):
    t = overview_path.read_text(encoding="utf-8")
    t = re.sub(r":::info (Testnet API reference|Archived API reference)\n.*?\n:::\n", "", t, flags=re.S)
    note = (f":::info {extra or 'API reference'}\n"
            f"Generated from `{stamp}` on {date.today().isoformat()} by scripts/api_version.py.\n:::\n")
    lines = t.split("\n")
    for i, l in enumerate(lines):
        if l.startswith("# "):
            lines.insert(i + 1, "\n" + note)
            break
    overview_path.write_text("\n".join(lines), encoding="utf-8")


def cmd_testnet(args):
    d, w = generate_pair(args.zanod, args.simplewallet)
    target = VDOCS / "version-testnet"
    if not target.exists():
        die("version-testnet does not exist; create it once manually or restore from git")
    replace_generated(target, d, w)
    add_provenance(target / "overview.md", stamp_of(d), "Testnet API reference")
    set_config_label("testnet", args.label)
    normalize_versions_json()
    print("testnet snapshot refreshed — run `check`, build, and review the diff before committing")


def cmd_archive(args):
    name = args.name
    target = VDOCS / f"version-{name}"
    if target.exists():
        die(f"version-{name} already exists")
    if subprocess.run(["git", "-C", str(ROOT), "diff", "--quiet", "--", "api-reference"]).returncode != 0:
        die("api-reference/ has uncommitted changes; archive from a clean, pinned state")
    shutil.copytree(WORK, target)
    (VSIDE / f"version-{name}-sidebars.json").write_text(
        json.dumps(SIDEBAR_TEMPLATE, indent=2) + "\n", encoding="utf-8")
    add_provenance(target / "overview.md", stamp_of(WORK / "daemon-rpc-api"), "Archived API reference")
    versions = json.loads(VJSON.read_text(encoding="utf-8"))
    if name not in versions:
        versions.append(name)
        VJSON.write_text(json.dumps(versions) + "\n", encoding="utf-8")
    normalize_versions_json()
    print(f"archived current mainnet as version-{name} (label/path/banner use Docusaurus defaults)")


def release_line(stamp):
    """'2.2.1.502[72b939e]' -> '2.2.1' (MAJOR.MINOR.PATCH identifies a release line)."""
    m = re.match(r"v?(\d+\.\d+\.\d+)", stamp or "")
    return m.group(1) if m else None


def cmd_rollover(args):
    d, w = generate_pair(args.zanod, args.simplewallet)
    old_line = release_line(stamp_of(WORK / "daemon-rpc-api"))
    new_line = release_line(stamp_of(d))
    if old_line and new_line and old_line != new_line:
        # crossing a release boundary: preserve the old release before replacing it
        if not (VDOCS / f"version-{old_line}").exists():
            print(f"release boundary {old_line} -> {new_line}: auto-archiving {old_line} first")
            class _A: name = old_line
            cmd_archive(_A)
    elif not any(p.name.startswith("version-") and p.name != "version-testnet" for p in VDOCS.iterdir()):
        die("no archive snapshot exists — run `archive` first (rollover refuses to destroy history)")
    replace_generated(WORK, d, w)
    for page in INTRO_PAGES:
        if not (WORK / page).exists():
            die(f"hand-written page {page} missing after rollover — aborting, restore from git")
    set_config_label("current", args.label)
    print("mainnet rolled over — run `check`, build, review diff (expected delta only), then commit.")
    print("when the build bot commits later into docs/build/rpc-api/, verify it is a no-op vs api-reference/")


def cmd_check(_args):
    problems = []
    for page in INTRO_PAGES:
        if not (WORK / page).exists():
            problems.append(f"missing hand-written page: api-reference/{page}")
    if (WORK / "_category_.json").exists():
        problems.append("vestigial api-reference/_category_.json present")
    versions = json.loads(VJSON.read_text(encoding="utf-8"))
    if versions and "testnet" in versions and versions[0] != "testnet":
        problems.append(f"api_versions.json order wrong (testnet must be first): {versions}")
    for v in versions:
        if not (VDOCS / f"version-{v}").is_dir():
            problems.append(f"version '{v}' listed but api_versioned_docs/version-{v} missing")
        if not (VSIDE / f"version-{v}-sidebars.json").is_file():
            problems.append(f"sidebars json missing for version '{v}'")
    cfg = CONFIG.read_text(encoding="utf-8")
    stamp = stamp_of(WORK / "daemon-rpc-api") or ""
    m = re.search(r'current: \{\n\s*label: "Mainnet \(([^)]+)\)"', cfg)
    if m and m.group(1) not in stamp:
        problems.append(f"current label '{m.group(1)}' does not match page stamp '{stamp}'")
    if problems:
        print("CHECK FAILED:")
        for p in problems:
            print("  -", p)
        sys.exit(1)
    print(f"check OK: {len(versions)} snapshot(s) {versions}, mainnet stamp {stamp}")


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = ap.add_subparsers(dest="cmd", required=True)
    for name, fn, needs in (
        ("testnet", cmd_testnet, True),
        ("archive", cmd_archive, False),
        ("rollover", cmd_rollover, True),
        ("check", cmd_check, False),
    ):
        p = sub.add_parser(name)
        p.set_defaults(fn=fn)
        if needs:
            p.add_argument("--zanod", required=True)
            p.add_argument("--simplewallet", required=True)
            p.add_argument("--label", required=True)
        elif name == "archive":
            p.add_argument("--name", required=True, help="release name, e.g. 2.2.1")
    args = ap.parse_args()
    args.fn(args)


if __name__ == "__main__":
    main()
